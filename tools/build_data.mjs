// Builds public/data.js (used by the pages and the server) from tools/characters.json.
// Usage: node tools/build_data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const src = JSON.parse(readFileSync(new URL('./characters.json', import.meta.url)));

// Players → [townsfolk, outsider, minion, demon]. The standard setup table (printed on the game's Traveller sheet);
// checked against the open-source Pocket Grimoire config (config/game.yaml).
const COUNTS = { 5: [3, 0, 1, 1], 6: [3, 1, 1, 1], 7: [5, 0, 1, 1], 8: [5, 1, 1, 1], 9: [5, 2, 1, 1], 10: [7, 0, 2, 1],
  11: [7, 1, 2, 1], 12: [7, 2, 2, 1], 13: [9, 0, 3, 1], 14: [9, 1, 3, 1], 15: [9, 2, 3, 1] };
const TEAM_ZH = { townsfolk: '镇民', outsider: '外来者', minion: '爪牙', demon: '恶魔' };

const EDITIONS = Object.fromEntries(src.editions.map(e => [e.id, { zh: e.zh, en: e.en, alias: e.alias || [],
  chars: src.characters.filter(c => c.edition === e.id).map(c => c.id) }]));
const CHARS = Object.fromEntries(src.characters.map(c => [c.id, {
  zh: c.zh, en: c.en, ed: c.edition, team: c.team, gist: c.gist,
  fn: c.firstNight, on: c.otherNight, stF: c.stFirst, stO: c.stOther,
  rem: [...new Set([...(c.reminders || []), ...(c.remindersGlobal || [])])],   // kinds only: the real box has several of some
  setup: !!c.setup, setupNote: c.setupNote || '', om: c.outsiderMod || [0]
}]));
const STEPS = Object.fromEntries(src.nightSteps.map(s => [s.id, { zh: s.zh, fn: s.firstNight, on: s.otherNight, stF: s.stFirst, stO: s.stOther }]));

const out = `// Generated by tools/build_data.mjs from tools/characters.json. Do not edit by hand.
// Character names: the official Chinese names (集石钟楼百科). Summaries (gist) and Storyteller tips (stF/stO): this site's own words.
// Night order numbers (fn: first night, on: other nights; 0 = doesn't wake): positions in the official nightsheet.json
// (ThePandemoniumInstitute/botc-release). rem: reminder tokens. om: possible Outsider count changes at setup.
export const COUNTS = ${JSON.stringify(COUNTS)};
export const TEAM_ZH = ${JSON.stringify(TEAM_ZH)};
export const EDITIONS = ${JSON.stringify(EDITIONS, null, 1)};
export const STEPS = ${JSON.stringify(STEPS, null, 1)};
export const CHARS = ${JSON.stringify(CHARS, null, 1)};
`;
writeFileSync(new URL('../public/data.js', import.meta.url), out);
console.log(Object.keys(CHARS).length, 'characters');
